#!/usr/bin/env bash
# Write secret.env for the evaluation stack with fresh random values, and add a
# POSTGRES_PASSWORD to .env (read by compose.postgres.yaml) when .env has none.
# Usage: ./make_secrets.sh [--force]
#   --force  write the licence again (from TYK_AI_LICENSE) and keep every other
#            value: AI Studio 2.3 encrypts stored keys with TYK_AI_SECRET_KEY, so
#            a new value would make the stored App keys and LLM keys unreadable.
# An Enterprise licence (one issued for AI Studio 2.3) is read from the
# TYK_AI_LICENSE environment variable when it is set; the value is never printed.
set -euo pipefail
cd "$(dirname "$0")"

hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
keep() { grep "^$1=" secret.env 2>/dev/null | head -1 | cut -d= -f2- || true; }

# Kept across --force: a PostgreSQL volume keeps the password it was created with.
if ! grep -q '^POSTGRES_PASSWORD=' .env 2>/dev/null; then
  if [ -s .env ] && [ -n "$(tail -c1 .env)" ]; then echo >> .env; fi
  echo "POSTGRES_PASSWORD=$(hex 16)" >> .env
  chmod 600 .env
  echo "added POSTGRES_PASSWORD to .env"
fi

if [ -f secret.env ] && [ "${1:-}" != "--force" ]; then
  echo "secret.env already exists (use --force to write the licence again)" >&2
  exit 0
fi

grpc_token="$(keep GRPC_AUTH_TOKEN)";               grpc_token="${grpc_token:-$(hex 24)}"
encryption_key="$(keep MICROGATEWAY_ENCRYPTION_KEY)"; encryption_key="${encryption_key:-$(hex 16)}"   # exactly 32 characters
jwt_secret="$(keep JWT_SECRET)";                     jwt_secret="${jwt_secret:-$(hex 32)}"
secret_key="$(keep TYK_AI_SECRET_KEY)";              secret_key="${secret_key:-$(hex 32)}"
metrics_token="$(keep METRICS_AUTH_TOKEN)";          metrics_token="${metrics_token:-$(hex 24)}"
umask 077
{
  echo "# Generated by make_secrets.sh. Do not commit."
  echo "TYK_AI_LICENSE=${TYK_AI_LICENSE:-}"
  echo "# Hub and edge must agree on these two pairs."
  echo "GRPC_AUTH_TOKEN=${grpc_token}"
  echo "EDGE_AUTH_TOKEN=${grpc_token}"
  echo "MICROGATEWAY_ENCRYPTION_KEY=${encryption_key}"
  echo "ENCRYPTION_KEY=${encryption_key}"
  echo "JWT_SECRET=${jwt_secret}"
  echo "# Encrypts stored LLM keys, secrets and App keys. Never change it on a used database."
  echo "TYK_AI_SECRET_KEY=${secret_key}"
  echo "METRICS_AUTH_TOKEN=${metrics_token}"
} > secret.env.tmp
mv secret.env.tmp secret.env
echo "wrote secret.env"
